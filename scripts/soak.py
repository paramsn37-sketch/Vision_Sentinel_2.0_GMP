"""Soak test sampler (Phase 11): sample a running backend once a minute and write docs/eval/soak.{json,md,svg}.

python scripts/soak.py --pid <uvicorn pid> --minutes 60 [--url http://127.0.0.1:8000]
Records resident memory, open file handles and threads of the process, per-camera fps and frame counters from
/api/v1/metrics, and the database size. The report states whether memory grew by more than 10 % after warm-up.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import time
import urllib.request
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "eval"


def proc(pid: int) -> dict:
    status = Path(f"/proc/{pid}/status").read_text()
    rss_kb = int(re.search(r"VmRSS:\s+(\d+)", status)[1])
    threads = int(re.search(r"Threads:\s+(\d+)", status)[1])
    return {"rss_mb": round(rss_kb / 1024, 1), "fds": len(os.listdir(f"/proc/{pid}/fd")), "threads": threads}


def metrics(url: str) -> dict:
    text = urllib.request.urlopen(f"{url}/api/v1/metrics", timeout=10).read().decode()
    fps = {m[1]: float(m[2]) for m in re.finditer(r'vs_camera_fps\{camera="([^"]+)"\} ([\d.]+)', text)}
    frames = {
        m[1]: int(float(m[2]))
        for m in re.finditer(r'vs_camera_frames_total\{camera="([^"]+)"\} ([\d.]+)', text)
    }
    return {"fps": fps, "frames": frames}


def svg(samples: list[dict]) -> str:
    w, h, pad = 640, 220, 40
    xs = [s["minute"] for s in samples]
    ys = [s["rss_mb"] for s in samples]
    top = max(ys) * 1.15
    x = lambda v: pad + (v - xs[0]) / max(1, xs[-1] - xs[0]) * (w - pad - 10)  # noqa: E731
    y = lambda v: h - 24 - v / top * (h - 44)  # noqa: E731
    pts = " ".join(f"{x(a):.1f},{y(b):.1f}" for a, b in zip(xs, ys, strict=True))
    ticks = "".join(
        f'<line x1="{pad}" x2="{w - 10}" y1="{y(t):.1f}" y2="{y(t):.1f}" stroke="#ddd"/>'
        f'<text x="{pad - 6}" y="{y(t) + 4:.1f}" font-size="11" text-anchor="end" fill="#555">{t:.0f}</text>'
        for t in [top * k / 4 for k in range(5)]
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" font-family="sans-serif">'
        f'<rect width="100%" height="100%" fill="#fff"/>{ticks}'
        f'<text x="{pad}" y="14" font-size="12" fill="#222">Backend resident memory (MB) per minute of the soak</text>'
        f'<polyline points="{pts}" fill="none" stroke="#1d64c2" stroke-width="2"/>'
        f'<text x="{pad}" y="{h - 6}" font-size="11" fill="#555">minute {xs[0]}</text>'
        f'<text x="{w - 10}" y="{h - 6}" font-size="11" fill="#555" text-anchor="end">minute {xs[-1]}</text></svg>'
    )


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pid", type=int, required=True)
    ap.add_argument("--minutes", type=int, default=60)
    ap.add_argument("--url", default="http://127.0.0.1:8000")
    ap.add_argument("--db", type=Path, default=ROOT / "data" / "runtime" / "vision_sentinel.db")
    args = ap.parse_args()

    samples = []
    t0 = time.time()
    for minute in range(args.minutes + 1):
        s = {"minute": minute, "at": datetime.now(UTC).isoformat(timespec="seconds"), **proc(args.pid)}
        s.update(metrics(args.url))
        s["db_mb"] = round(sum(p.stat().st_size for p in args.db.parent.glob(args.db.name + "*")) / 2**20, 2)
        samples.append(s)
        print(json.dumps(s), flush=True)
        if minute < args.minutes:
            time.sleep(max(0.0, t0 + 60 * (minute + 1) - time.time()))

    warm = samples[min(5, len(samples) - 1)]  # after model load, caches and first incidents
    last = samples[-1]
    growth = (last["rss_mb"] - warm["rss_mb"]) / warm["rss_mb"]
    first_frames, last_frames = samples[0]["frames"], last["frames"]
    stalled = [c for c in last_frames if last_frames[c] <= first_frames.get(c, 0)]
    verdict = {
        "rss_growth_after_warmup": round(growth, 4),
        "memory_flat": growth <= 0.10,
        "fd_range": [min(s["fds"] for s in samples), max(s["fds"] for s in samples)],
        "thread_range": [min(s["threads"] for s in samples), max(s["threads"] for s in samples)],
        "stalled_cameras": stalled,
        "load_avg_1m_end": round(os.getloadavg()[0], 2),
    }
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "soak.json").write_text(json.dumps({"verdict": verdict, "samples": samples}, indent=1) + "\n")
    (OUT / "soak.svg").write_text(svg(samples))
    rows = "\n".join(
        f"| {s['minute']} | {s['rss_mb']} | {s['fds']} | {s['threads']} | {s['db_mb']} | "
        + ", ".join(f"{c} {v:.1f}" for c, v in sorted(s["fps"].items()))
        + " |"
        for s in samples
        if s["minute"] % 5 == 0 or s is last
    )
    (OUT / "soak.md").write_text(
        f"# Soak test\n\nGenerated by `scripts/soak.py`: {args.minutes} minutes, {len(last_frames)} looping file cameras, "
        f"sampled once a minute.\n\n![memory](soak.svg)\n\n"
        f"**Memory growth after warm-up (minute 5 → {last['minute']}): {growth:+.1%}** "
        f"({'within' if verdict['memory_flat'] else 'over'} the 10 % limit). Open files {verdict['fd_range'][0]}–"
        f"{verdict['fd_range'][1]}, threads {verdict['thread_range'][0]}–{verdict['thread_range'][1]}. "
        f"Cameras that stopped advancing: {', '.join(stalled) or 'none'}.\n\n"
        f"| minute | RSS MB | open files | threads | DB MB | fps per camera |\n|---|---|---|---|---|---|\n{rows}\n"
    )


if __name__ == "__main__":
    main()
