"""Build the sample clips in data/samples/ from the MOT17 half-length subset and record ground-truth counts.

Unique-person ground truth = distinct IDs of MOT class 1 (pedestrian) with the `consider` flag set, the standard
MOTChallenge evaluation definition. Static people (class 7) are reported separately.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
MOT = REPO / "data" / "raw" / "mot17" / "MOT17-50" / "train"
OUT = REPO / "data" / "samples"
CLIPS = {"MOT17-09": "street_corner", "MOT17-02": "town_square", "MOT17-04": "pedestrian_street_night"}
WIDTH = 960


def gt_counts(seq: Path) -> dict[str, int]:
    ped, static = set(), set()
    for line in (seq / "gt" / "gt.txt").read_text().split():
        f = line.split(",")
        tid, consider, cls = int(f[1]), int(f[6]), int(f[7])
        if consider == 1 and cls == 1:
            ped.add(tid)
        if cls == 7:
            static.add(tid)
    return {"unique_pedestrians": len(ped), "unique_static_persons": len(static)}


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    meta = {}
    for seq_name, nice in CLIPS.items():
        seq = MOT / seq_name
        frames = len(list((seq / "img1").glob("*.jpg")))
        dst = OUT / f"{nice}.mp4"
        subprocess.run(
            [
                "ffmpeg",
                "-y",
                "-loglevel",
                "error",
                "-framerate",
                "30",
                "-i",
                str(seq / "img1" / "%06d.jpg"),
                "-vf",
                f"scale={WIDTH}:-2",
                "-c:v",
                "libx264",
                "-preset",
                "slow",
                "-crf",
                "28",
                "-pix_fmt",
                "yuv420p",
                "-movflags",
                "+faststart",
                str(dst),
            ],
            check=True,
        )
        meta[nice] = {
            "file": f"data/samples/{dst.name}",
            "source": f"MOT17 {seq_name} (second half, from the boxmot MOT17-50 release)",
            "frames": frames,
            "fps": 30,
            "ground_truth": gt_counts(seq),
            "gt_path": f"data/raw/mot17/MOT17-50/train/{seq_name}/gt/gt.txt",
        }
    (REPO / "data" / "eval" / "clips.yaml").write_text(
        "# Sample clips with ground truth (generated by backend/eval/make_clips.py)\n"
        + yaml.safe_dump(meta, sort_keys=False)
    )
    print(yaml.safe_dump(meta, sort_keys=False))


if __name__ == "__main__":
    main()
