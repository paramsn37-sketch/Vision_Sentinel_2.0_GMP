"""Build the sample clips in data/samples/ from the MOT17 half-length subset and record ground-truth counts.

Unique-person ground truth = distinct IDs of MOT class 1 (pedestrian) with the `consider` flag set, the standard
MOTChallenge evaluation definition. Static people (class 7) are reported separately.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
MOT = REPO / "data" / "raw" / "mot17" / "MOT17-50" / "train"
OUT = REPO / "data" / "samples"
CLIPS = {"MOT17-09": "street_corner", "MOT17-02": "town_square", "MOT17-04": "pedestrian_street_night"}
WIDTH = 960


def gt_counts(seq: Path) -> dict[str, int]:
    ped, static = set(), set()
    for line in (seq / "gt" / "gt.txt").read_text().split():
        f = line.split(",")
        tid, consider, cls = int(f[1]), int(f[6]), int(f[7])
        if consider == 1 and cls == 1:
            ped.add(tid)
        if cls == 7:
            static.add(tid)
    return {"unique_pedestrians": len(ped), "unique_static_persons": len(static)}


def ppe_slideshow(n_images: int = 18, hold_s: float = 4.0, fps: int = 10) -> dict:
    """Still Construction-PPE test images, each held for `hold_s`, letterboxed to 960×540.

    Only images with at least one person, and a mix of helmet / bare head / vest, are used. This is a demo source for
    PPE states on the Live page; it is not continuous video.
    """
    import cv2
    import numpy as np

    test_imgs = REPO / "data" / "merged" / "test" / "images"
    labels = REPO / "data" / "merged" / "test" / "labels"
    picked = []
    for img in sorted(test_imgs.glob("construction_ppe__*.jpg")):
        cls = [
            int(line.split()[0])
            for line in (labels / f"{img.stem}.txt").read_text().split("\n")
            if line.strip()
        ]
        if 0 in cls and (1 in cls or 2 in cls) and cls.count(0) <= 4:
            picked.append(img)
    rng = np.random.default_rng(3)
    rng.shuffle(picked)
    picked = sorted(picked[:n_images])
    dst = OUT / "ppe_slideshow.mp4"
    tmp = OUT / "ppe_slideshow.avi"
    w, h = 960, 540
    vw = cv2.VideoWriter(str(tmp), cv2.VideoWriter_fourcc(*"MJPG"), fps, (w, h))
    for p in picked:
        img = cv2.imread(str(p))
        s = min(w / img.shape[1], h / img.shape[0])
        r = cv2.resize(img, (int(img.shape[1] * s), int(img.shape[0] * s)), interpolation=cv2.INTER_AREA)
        canvas = np.full((h, w, 3), 24, np.uint8)
        y0, x0 = (h - r.shape[0]) // 2, (w - r.shape[1]) // 2
        canvas[y0 : y0 + r.shape[0], x0 : x0 + r.shape[1]] = r
        for _ in range(int(hold_s * fps)):
            vw.write(canvas)
    vw.release()
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(tmp), "-c:v", "libx264", "-preset", "slow", "-crf", "26",
                    "-pix_fmt", "yuv420p", "-movflags", "+faststart", str(dst)], check=True)  # fmt: skip
    tmp.unlink()
    return {
        "file": f"data/samples/{dst.name}",
        "images": [p.name for p in picked],
        "hold_s": hold_s,
        "fps": fps,
    }


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    meta = {}
    for seq_name, nice in CLIPS.items():
        seq = MOT / seq_name
        frames = len(list((seq / "img1").glob("*.jpg")))
        dst = OUT / f"{nice}.mp4"
        subprocess.run(
            [
                "ffmpeg",
                "-y",
                "-loglevel",
                "error",
                "-framerate",
                "30",
                "-i",
                str(seq / "img1" / "%06d.jpg"),
                "-vf",
                f"scale={WIDTH}:-2",
                "-c:v",
                "libx264",
                "-preset",
                "slow",
                "-crf",
                "28",
                "-pix_fmt",
                "yuv420p",
                "-movflags",
                "+faststart",
                str(dst),
            ],
            check=True,
        )
        meta[nice] = {
            "file": f"data/samples/{dst.name}",
            "source": f"MOT17 {seq_name} (second half, from the boxmot MOT17-50 release)",
            "frames": frames,
            "fps": 30,
            "ground_truth": gt_counts(seq),
            "gt_path": f"data/raw/mot17/MOT17-50/train/{seq_name}/gt/gt.txt",
        }
    meta["ppe_slideshow"] = ppe_slideshow()
    (REPO / "data" / "eval" / "clips.yaml").write_text(
        "# Sample clips with ground truth (generated by backend/eval/make_clips.py)\n"
        + yaml.safe_dump(meta, sort_keys=False)
    )
    print(yaml.safe_dump(meta, sort_keys=False))


if __name__ == "__main__":
    main()
