"""Generate data/DATASET_CARD.md and data/figures/* from the merged dataset (numbers are computed, never typed)."""

from __future__ import annotations

import json
import random
import sys
from collections import Counter, defaultdict
from pathlib import Path

import cv2
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from vs_data.classmap import load_class_map
from vs_data.paths import FIGURES, MERGED, RAW, REPO

SPLITS = ("train", "val", "test")
LICENCES = {
    "construction_ppe": "AGPL-3.0 (Ultralytics Construction-PPE)",
    "openimages_v7": "Annotations CC BY 4.0, images CC BY 2.0 (Open Images V7)",
}


def read_labels(split: str):
    for lbl in sorted((MERGED / split / "labels").glob("*.txt")):
        rows = [line.split() for line in lbl.read_text().split("\n") if line.strip()]
        yield lbl.stem, [(int(r[0]), *map(float, r[1:])) for r in rows]


def main() -> None:
    cm = load_class_map()
    FIGURES.mkdir(parents=True, exist_ok=True)
    per_split = {s: Counter() for s in SPLITS}
    per_source_imgs: dict[str, Counter] = defaultdict(Counter)
    per_source_inst: dict[str, Counter] = defaultdict(Counter)
    box_area: dict[str, list[float]] = defaultdict(list)
    sizes = []
    for split in SPLITS:
        for stem, rows in read_labels(split):
            source = stem.split("__")[0]
            per_source_imgs[source][split] += 1
            img = cv2.imread(str(MERGED / split / "images" / f"{stem}.jpg"))
            if img is not None:
                sizes.append(img.shape[:2])
            for cls, _cx, _cy, w, h in rows:
                name = cm.taxonomy[cls]
                per_split[split][name] += 1
                per_source_inst[source][name] += 1
                box_area[name].append(float(np.sqrt(w * h)))

    # Figures
    fig, ax = plt.subplots(figsize=(8, 3.6))
    x = np.arange(len(cm.taxonomy))
    for i, split in enumerate(SPLITS):
        ax.bar(x + (i - 1) * 0.27, [per_split[split][c] for c in cm.taxonomy], 0.27, label=split)
    ax.set_xticks(x, cm.taxonomy, rotation=30, ha="right")
    ax.set_ylabel("instances")
    ax.set_title("Instances per class and split")
    ax.legend(frameon=False)
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(FIGURES / "class_distribution.png", dpi=130)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 3.6))
    ax.boxplot([box_area[c] or [0] for c in cm.taxonomy], tick_labels=cm.taxonomy, showfliers=False)
    ax.set_ylabel("sqrt(box area / image area)")
    ax.set_title("Relative box size per class")
    ax.tick_params(axis="x", rotation=30)
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(FIGURES / "box_sizes.png", dpi=130)
    plt.close(fig)

    # QA grids: random labelled train crops per class
    rng = random.Random(0)
    train = list(read_labels("train"))
    for ci, cname in enumerate(cm.taxonomy):
        cands = [(s, r) for s, rows in train for r in rows if r[0] == ci]
        tiles = []
        for stem, (_, cx, cy, w, h) in rng.sample(cands, min(36, len(cands))):
            img = cv2.imread(str(MERGED / "train" / "images" / f"{stem}.jpg"))
            H, W = img.shape[:2]
            pad = 0.25
            x1, y1 = int(max(0, (cx - w * (0.5 + pad)) * W)), int(max(0, (cy - h * (0.5 + pad)) * H))
            x2, y2 = int(min(W, (cx + w * (0.5 + pad)) * W)), int(min(H, (cy + h * (0.5 + pad)) * H))
            crop = img[y1:y2, x1:x2].copy()
            bx1, by1 = int((cx - w / 2) * W) - x1, int((cy - h / 2) * H) - y1
            bx2, by2 = int((cx + w / 2) * W) - x1, int((cy + h / 2) * H) - y1
            cv2.rectangle(crop, (bx1, by1), (bx2, by2), (0, 220, 255), 2)
            tiles.append(cv2.resize(crop, (120, 120)))
        while len(tiles) < 36:
            tiles.append(np.zeros((120, 120, 3), np.uint8))
        grid = np.vstack([np.hstack(tiles[r * 6 : r * 6 + 6]) for r in range(6)])
        cv2.imwrite(str(FIGURES / f"qa_{cname}.jpg"), grid, [cv2.IMWRITE_JPEG_QUALITY, 80])

    split_stats = json.loads((MERGED / "split_stats.json").read_text())
    oiv7 = json.loads((RAW / "oiv7" / "SOURCE.json").read_text())
    hs = np.array(sizes)
    lines = [
        "# Dataset card — Vision Sentinel PPE v2.0",
        "",
        "Generated by `training/scripts/dataset_card.py`. Images are not committed; manifests are in"
        " `data/manifests/` (test split checksum in `test_manifest.sha256`).",
        "",
        "## Taxonomy",
        "",
        "| id | class | meaning |",
        "|---|---|---|",
    ]
    meaning = {
        "person": "a person (whole or partly visible)",
        "head": "bare head, i.e. no hard hat",
        "helmet": "hard hat worn on a head",
        "vest": "high-visibility vest",
        "gloves": "gloved hand",
        "hand": "bare hand",
        "boots": "boots / safety footwear",
        "goggles": "eye protection worn",
        "no_goggles": "visible eyes without protection",
    }
    lines += [f"| {i} | {c} | {meaning[c]} |" for i, c in enumerate(cm.taxonomy)]
    lines += ["", "## Sources", "", "| source | train | val | test | licence |", "|---|---|---|---|---|"]
    for src, cnt in per_source_imgs.items():
        lines.append(f"| {src} | {cnt['train']} | {cnt['val']} | {cnt['test']} | {LICENCES.get(src, '?')} |")
    lines += [
        "",
        f"Near-duplicates removed by perceptual hash (Hamming ≤ 6): **{split_stats['deduplicated_away']}**.",
        f"Open Images selection: {json.dumps(oiv7['selection'])}; downloads failed: {oiv7['failed_downloads']}.",
        "",
        "## Instances per class",
        "",
        "| class | train | val | test | construction_ppe | openimages_v7 |",
        "|---|---|---|---|---|---|",
    ]
    for c in cm.taxonomy:
        lines.append(
            f"| {c} | {per_split['train'][c]} | {per_split['val'][c]} | {per_split['test'][c]} | "
            f"{per_source_inst['construction_ppe'][c]} | {per_source_inst['openimages_v7'][c]} |"
        )
    lines += [
        "",
        "![class distribution](figures/class_distribution.png)",
        "![box sizes](figures/box_sizes.png)",
        "",
        "## Image sizes",
        "",
        f"{len(hs)} images; height median {int(np.median(hs[:, 0]))} px (min {hs[:, 0].min()}, max"
        f" {hs[:, 0].max()}), width median {int(np.median(hs[:, 1]))} px (min {hs[:, 1].min()}, max {hs[:, 1].max()}).",
        "Open Images were downscaled to a 960 px long side at download time.",
        "",
        "## Known gaps and biases",
        "",
        "- `vest`, `helmet`, `no_goggles` come only from Construction-PPE (construction sites, daylight, mostly frontal).",
        "- Open Images labels are not exhaustive: an Open Images image can contain an unlabelled glove or hand. This"
        " adds label noise for `gloves`/`hand`; heads are labelled whenever the image was selected (selection rule).",
        "- Images labelled with sport/bicycle helmets were excluded, so motorbike helmets are unseen (may be confused"
        " with hard hats).",
        "- No face-mask class: no reachable source in the build environment (ADR-0006).",
        "- Few night, rain or thermal scenes; no top-down CCTV angles. Expect lower accuracy there.",
        "- Kaggle SH17 and Roboflow sets were not reachable (network policy), see ADR-0004.",
        "",
        "## Licence implications",
        "",
        "Construction-PPE is AGPL-3.0 and Open Images is CC BY; trained weights are released under AGPL-3.0 with"
        " attribution to both sources.",
        "",
        "## QA grids",
        "",
        "Random labelled training crops per class: `data/figures/qa_<class>.jpg`.",
    ]
    (REPO / "data" / "DATASET_CARD.md").write_text("\n".join(lines) + "\n")
    print("ok")


if __name__ == "__main__":
    main()
